#include <fstream>
#include <ostream>
#include <string>
#include <vector>

#include "splatcore/ply_io.h"

namespace splatcore {

Status write_ply(const SplatCloud& cloud, std::ostream& out) {
    if (cloud.sh_degree != 0 && cloud.sh_degree != 1) {
        return Status::failure("PLY export supports SH degree 0 or 1 only, got degree " +
                               std::to_string(cloud.sh_degree) + " (truncate first)");
    }
    if (!cloud.valid_sizes()) return Status::failure("SplatCloud has inconsistent array sizes");

    const int rest_per_channel = sh_rest_coeffs(cloud.sh_degree);
    std::string header;
    header += "ply\n";
    header += "format binary_little_endian 1.0\n";
    header += "comment generated by pocketsplat\n";
    header += "element vertex " + std::to_string(cloud.count) + "\n";
    for (const char* axis : {"x", "y", "z"}) header += std::string("property float ") + axis + "\n";
    for (int i = 0; i < 3; ++i) header += "property float f_dc_" + std::to_string(i) + "\n";
    for (int k = 0; k < 3 * rest_per_channel; ++k)
        header += "property float f_rest_" + std::to_string(k) + "\n";
    header += "property float opacity\n";
    for (int i = 0; i < 3; ++i) header += "property float scale_" + std::to_string(i) + "\n";
    for (int i = 0; i < 4; ++i) header += "property float rot_" + std::to_string(i) + "\n";
    header += "end_header\n";
    out.write(header.data(), static_cast<std::streamsize>(header.size()));

    const std::size_t ncols = 3 + 3 + 3 * static_cast<std::size_t>(rest_per_channel) + 1 + 3 + 4;
    std::vector<float> row(ncols);
    for (std::size_t i = 0; i < cloud.count; ++i) {
        std::size_t c = 0;
        for (int a = 0; a < 3; ++a) row[c++] = cloud.positions[3 * i + a];
        for (int a = 0; a < 3; ++a) row[c++] = cloud.dc[3 * i + a];
        // Coefficient-major in memory back to the planar-per-channel file layout.
        const float* sh = cloud.sh.data() + 3 * static_cast<std::size_t>(rest_per_channel) * i;
        for (int ch = 0; ch < 3; ++ch) {
            for (int k = 0; k < rest_per_channel; ++k) row[c++] = sh[k * 3 + ch];
        }
        row[c++] = cloud.opacities[i];
        for (int a = 0; a < 3; ++a) row[c++] = cloud.log_scales[3 * i + a];
        for (int a = 0; a < 4; ++a) row[c++] = cloud.rotations[4 * i + a];
        out.write(reinterpret_cast<const char*>(row.data()),
                  static_cast<std::streamsize>(ncols * sizeof(float)));
    }
    if (!out) return Status::failure("write failed");
    return Status::success();
}

Status write_ply(const SplatCloud& cloud, const std::filesystem::path& path) {
    std::ofstream file(path, std::ios::binary);
    if (!file) return Status::failure("cannot open '" + path.string() + "' for writing");
    Status status = write_ply(cloud, file);
    if (status.ok() && !file.flush()) return Status::failure("write failed on flush");
    return status;
}

}  // namespace splatcore
